test('every job runs on a GitHub-hosted runner: Linux for Node, Android and publishing, macos-26 for the Mac app', () => {
  assert.doesNotMatch(workflow, /self-hosted|runs-on:.*droid-office|Mac Mini|runner-toolchain|ci-artifacts|\$HOME\//);
  const runsOn = (job: string) => workflow.match(new RegExp(`^ {2}${job}:\\n[\\s\\S]*?\\n {4}runs-on: (.+)$`, 'm'))?.[1];
  for (const job of ['changes', 'checks', 'android', 'publish']) assert.equal(runsOn(job), 'ubuntu-latest', job);
  assert.equal(runsOn('mac'), 'macos-26');
  assert.deepEqual(
    [...workflow.matchAll(/^ {2}(\w+):\n(?: {4}.+\n)*? {4}runs-on:/gm)].map((match) => match[1]),
    ['changes', 'checks', 'mac', 'android', 'publish'],
  );

  assert.match(workflow, /actions\/setup-node@v7/);
  assert.match(workflow, /actions\/setup-java@v6/);
  assert.match(workflow, /gradle\/actions\/setup-gradle@v6/);
  assert.match(jobSteps('android').join('\n'), /java-version: 21/);

  // GitHub's Ubuntu image supplies the libraries; cached-browser checks must not need apt mirrors.
  assert.doesNotMatch(workflow, /sudo node node_modules\/playwright-core\/cli\.js install-deps chromium/);
  assert.match(workflow, /apparmor_parser -r \/etc\/apparmor\.d\/factory-flow-chromium/);
});

