test("a run's artifacts go between jobs through the artifact service and publish assembles the release from them", () => {
  for (const [job, name] of [
    ['mac', 'mac'],
    ['android', 'android'],
  ]) {
    const upload = jobSteps(job).find((step) => step.includes('actions/upload-artifact@v7'));
    assert.ok(upload, job);
    assert.match(upload, new RegExp(`name: ${name}\\n`), job);
    assert.match(upload, /if-no-files-found: error/, job);
    assert.equal(stepRuns(upload), false, `${job}: PR`);
    assert.equal(stepRuns(upload, 'push', 'refs/heads/main'), true, `${job}: main`);
  }
  const mac = jobSteps('mac').join('\n');
  for (const file of ['release/*.dmg', 'release/*.zip', 'release/*.blockmap', 'release/latest-mac.yml']) assert.ok(mac.includes(`            ${file}\n`), file);
  const publish = jobSteps('publish').join('\n');
  assert.match(publish, /actions\/download-artifact@v8/);
  assert.match(publish, /merge-multiple: true/);
  // Staged in the runner's temp folder, never the workspace, so only this run's files go on the release.
  assert.match(publish, /path: \$\{\{ runner\.temp \}\}\/assets/);
  assert.match(publish, /working-directory: \$\{\{ runner\.temp \}\}/);
});

