export type MdIconName = keyof typeof PATHS;

/** A 24-unit Lucide stroke icon as an inline SVG, `size` pixels square, hidden from screen readers. */
export function mdIcon(name: MdIconName, size = 16): SVGSVGElement {
  const svg = document.createElementNS('http://www.w3.org/2000/svg', 'svg');
  for (const [k, v] of Object.entries({
    viewBox: '0 0 24 24',
    width: size,
    height: size,
    fill: 'none',
    stroke: 'currentColor',
    'stroke-width': 2,
    'stroke-linecap': 'round',
    'stroke-linejoin': 'round',
    'aria-hidden': 'true',
    class: 'icon',
  }))
    svg.setAttribute(k, String(v));
  svg.innerHTML = PATHS[name];
  return svg;
}

/** Copies `text`, then shows `doneLabel` and a check on `btn` (icon-only) for `ms`, as Factory's copy buttons do. */
export function wireIconCopy(btn: HTMLButtonElement, getText: () => string, labels: { idle: string; done: string }, opts: { size?: number; ms?: number } = {}): void {
  const size = opts.size ?? 12;
  let timer: ReturnType<typeof setTimeout> | undefined;
  const show = (done: boolean) => {
    btn.replaceChildren(mdIcon(done ? 'check' : 'copy', size));
    btn.setAttribute('aria-label', done ? labels.done : labels.idle);
    btn.title = done ? labels.done : labels.idle;
    btn.classList.toggle('copied', done);
  };
  show(false);
  btn.addEventListener('click', (e) => {
    e.stopPropagation();
    const clip = typeof navigator !== 'undefined' ? navigator.clipboard : undefined;
    if (!clip?.writeText) return;
    void clip
      .writeText(getText())
      .then(() => {
        show(true);
        if (timer !== undefined) clearTimeout(timer);
        timer = setTimeout(() => {
          timer = undefined;
          show(false);
        }, opts.ms ?? 2000);
      })
      .catch(() => {});
  });
}
